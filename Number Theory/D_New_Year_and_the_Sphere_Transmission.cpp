#include <bits/stdc++.h>
using namespace std;
using ll = long long;

// TLE for sure
void solve()
{
    ll n;
    cin >> n;

    set<ll> st;
    st.insert((n * (n + 1)) / 2); // for k = 1
    st.insert(1);                 // for k = n;

    for (ll k = 2; k < n; k++)
    {
        set<ll> temp;
        temp.insert(1);
        ll idx = 1;
        idx += k;
        if (idx > n)
        {
            idx %= n;
        }
        while (idx != 1)
        {
            temp.insert(idx);
            idx += k;
            if (idx > n)
            {
                idx %= n;
            }
        }
        ll sum = 0;
        for (const auto &t : temp)
        {
            sum += t;
        }
        st.insert(sum);
    }

    for (const auto &s : st)
    {
        cout << s << " ";
    }
    cout << endl;
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    // cin >> t;
    while (t--)
    {
        solve();
    }
}

