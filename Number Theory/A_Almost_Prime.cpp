#include <bits/stdc++.h>
using namespace std;
using ll = long long;

void solve()
{
    int n;
    cin >> n;
    if (n < 6)
    {
        cout << 0 << "\n";
        return;
    }
    vector<int> sieve(n + 1, 0);

    for (int i = 2; i <= n; i += 2)
    {
        sieve[i]++;
    }

    for (int i = 3; i <= n; i++)
    {
        if (!sieve[i])
        {
            for (int j = i; j <= n; j += i)
            {
                sieve[j]++;
            }
        }
    }

    int count = 0;
    for (int i = 6; i <= n; i++)
    {
        if (sieve[i] == 2)
        {
            count++;
        }
    }
    cout << count << "\n";
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    // cin >> t;
    while (t--)
    {
        solve();
    }
}

