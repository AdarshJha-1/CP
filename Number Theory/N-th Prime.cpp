#include <bits/stdc++.h>
using namespace std;
using ll = long long;

void solve()
{
    int n;
    cin >> n;

    vector<bool> sieve(1e7 + 1, true);
    sieve[0] = sieve[1] = false;

    for (int i = 4; i <= 1e7; i += 2)
    {
        sieve[i] = false;
    }

    for (int i = 3; i * i <= 1e7; i++)
    {
        if (sieve[i])
        {
            for (int j = i * i; j <= 1e7; j += 2 * i)
            {
                sieve[j] = false;
            }
        }
    }

    int i = 2;
    while (n >= 1)
    {
        if (sieve[i])
        {
            n--;
        }
        i++;
    }

    cout << i - 1 << "\n";
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    // cin >> t;
    while (t--)
    {
        solve();
    }
}

