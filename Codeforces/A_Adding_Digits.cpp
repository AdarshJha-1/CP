#include <bits/stdc++.h>
using namespace std;
using ll = long long;

void solve()
{
    ll a, b, n;
    cin >> a >> b >> n;

    n -= 1;

    bool found = false;
    for (ll i = 0; i <= 9; ++i)
    {
        if ((a * 10 + i) % b == 0)
        {
            cout << (a * 10 + i);
            found = true;
            break;
        }
    }

    if (!found)
    {
        cout << -1 << '\n';
    }
    else
    {
        while (n--)
        {
            cout << '0';
        }
    }
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    // cin >> t;
    while (t--)
    {
        solve();
    }
}

