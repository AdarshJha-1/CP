#include <bits/stdc++.h>
using namespace std;
using ll = long long;

// you know what fuck AI

bool isPalin(ll num)
{
    string temp = to_string(num);
    int i = 0;
    int j = temp.size() - 1;

    while (i <= j)
    {
        if (temp[i] == temp[j])
        {
            i++;
            j--;
        }
        else
        {
            return false;
        }
    }

    return true;
}

void solve()
{
    ll n;
    cin >> n;
    ll a = 0;
    ll b = (n / 12) * 12;

    while (b >= 0)
    {
        a = n - b;
        if (isPalin(a))
        {
            cout << a << " " << b << endl;
            return;
        }
        b -= 12;
    }

    cout << -1 << endl;
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t;
    cin >> t;

    while (t--)
        solve();
}

