#include <bits/stdc++.h>
using namespace std;
using ll = long long;

void solve()
{
    int n;
    cin >> n;
    vector<ll> arr(n, 0);
    for (int i = 0; i < n; i++)
    {
        cin >> arr[i];
    }

    sort(arr.rbegin(), arr.rend());
    if (arr[n - 1] <= 0)
    {
        cout << -1 << "\n";
        return;
    }
    ll x = arr[0];
    ll y = arr[1];
    for (int i = 2; i < n; i++)
    {
        if (y == 0)
        {
            cout << -1 << endl;
            return;
        }
        ll temp = x % y;
        if (temp == arr[i])
        {
            x = y;
            y = temp;
        }
        else
        {
            cout << -1 << endl;
            return;
        }
    }

    cout << arr[0] << " " << arr[1] << endl;
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    cin >> t;
    while (t--)
    {
        solve();
    }
}

