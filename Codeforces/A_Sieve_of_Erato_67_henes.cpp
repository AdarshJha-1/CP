#include <bits/stdc++.h>
using namespace std;
using ll = long long;

void solve()
{
    int n;
    cin >> n;
    bool found = false;
    for (int i = 0; i < n; i++)
    {
        int v;
        cin >> v;
        if (v == 67)
        {
            found = true;
        }
    }
    cout << (found ? "YES\n" : "NO\n");
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    cin >> t;
    while (t--)
    {
        solve();
    }
}

