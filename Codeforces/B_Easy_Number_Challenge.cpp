#include <bits/stdc++.h>
using namespace std;
using ll = long long;

int numOfDiv(int num)
{
    int cnt = 2;
    for (int i = 2; i * i <= num; ++i)
    {
        if (num % i == 0)
        {
            if (i * i == num)
            {
                cnt += 1;
            }
            else
            {
                cnt += 2;
            }
        }
    }

    return cnt;
}

void solve()
{
    int a, b, c;
    cin >> a >> b >> c;

    int ans = 0;
    for (int i = 1; i <= a; ++i)
    {
        for (int j = 1; j <= b; ++j)
        {
            for (int k = 1; k <= c; ++k)
            {
                int num = i * j * k;
                int temp = 0;
                if (num <= 2)
                {
                    temp = num;
                }
                else
                {
                    temp = numOfDiv(num);
                }
                ans += temp;

                // printf("%d x %d x %d -> %d :: %d\n", i, j, k, num, temp);
            }
        }
    }
    cout << (ans % 1073741824) << "\n";
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    // cin >> t;
    while (t--)
    {
        solve();
    }
}

