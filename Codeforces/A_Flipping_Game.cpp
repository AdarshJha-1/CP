#include <bits/stdc++.h>
using namespace std;
using ll = long long;
const ll INF = 1e18;
const ll MOD = 1e9 + 7;

void solve()
{
    int n;
    cin >> n;
    vector<int> arr(n);
    for (auto &a : arr)
    {
        cin >> a;
    }

    int ans = 0;
    for (int i = 0; i < n; i++)
    {
        for (int j = i; j < n; j++)
        {
            int cnt = 0;
            for (int k = i - 1; k >= 0; k--)
            {
                cnt += (arr[k] == 1);
            }
            for (int k = i; k <= j; k++)
            {
                cnt += (arr[k] == 0);
            }
            for (int k = j + 1; k < n; k++)
            {
                cnt += (arr[k] == 1);
            }
            ans = max(ans, cnt);
        }
    }

    cout << ans << '\n';
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    // cin >> t;
    while (t--)
    {
        solve();
    }
}

