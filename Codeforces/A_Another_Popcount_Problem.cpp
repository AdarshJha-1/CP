#include <bits/stdc++.h>
using namespace std;
using ll = long long;

void solve()
{
    long long n, k;
    cin >> n >> k;

    priority_queue<long long, vector<long long>, greater<long long>> pq;

    for (long long i = 0; i < k; i++)
    {
        pq.push(1);
    }

    long long ans = 0;

    while (!pq.empty())
    {
        long long cost = pq.top();
        pq.pop();

        if (cost > n)
        {
            break;
        }

        n -= cost;
        ans++;

        pq.push(cost * 2);
    }

    cout << ans << '\n';
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    cin >> t;
    while (t--)
    {
        solve();
    }
}

