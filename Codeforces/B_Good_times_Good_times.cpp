void solve()
{
    string x;
    cin >> x;
    int L = x.length();

    long long y = 1;
    for (int i = 0; i < L; i++)
    {
        y *= 10;
    }
    y += 1;
    cout << y << "\n";
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    cin >> t;
    while (t--)
    {
        solve();
    }
}

