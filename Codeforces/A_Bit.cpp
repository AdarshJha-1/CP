#include <bits/stdc++.h>
using namespace std;
using ll = long long;

void solve()
{
    int x = 0;
    int n;
    cin >> n;
    while (n--)
    {
        string q;
        cin >> q;
        if (q == "++X")
        {
            ++x;
        }
        if (q == "--X")
        {
            --x;
        }
        if (q == "X++")
        {
            x++;
        }
        if (q == "X--")
        {
            x--;
        }
    }
    cout << x << "\n";
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    // cin >> t;
    while (t--)
    {
        solve();
    }
}

