#include <bits/stdc++.h>
using namespace std;
using ll = long long;
const ll INF = 1e18;
const ll MOD = 1e9 + 7;

void solve()
{
    ll n, x, y;
    cin >> n >> x >> y;
    vector<ll> arr(n);
    for (auto &a : arr)
    {
        cin >> a;
    }

    int cnt = 0;

    for (int i = 0; i < n - 1; i++)
    {
        for (int j = i + 1; j < n; j++)
        {
            if ((arr[i] + arr[j]) % x == 0 && (arr[i] - arr[j]) % y == 0)
            {
                cnt++;
            }
        }
    }
    cout << cnt << '\n';
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    cin >> t;
    while (t--)
    {
        solve();
    }
}

