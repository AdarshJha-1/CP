#include <bits/stdc++.h>
using namespace std;
using ll = long long;

void solve()
{
    int k;
    cin >> k;

    int over2Cnt = 0;
    int over3Cnt = 0;

    while (k--)
    {
        ll v;
        cin >> v;
        if (v >= 2)
        {
            over2Cnt++;
        }
        if (v >= 3)
        {
            over3Cnt++;
        }
    }

    if (over2Cnt >= 2 || over3Cnt >= 1)
    {
        cout << "YES\n";
    }
    else
    {
        cout << "NO\n";
    }
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    cin >> t;
    while (t--)
    {
        solve();
    }
}

