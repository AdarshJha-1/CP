#include <bits/stdc++.h>
using namespace std;
using ll = long long;

void solve()
{
    ll n;
    cin >> n;
    vector<ll> arr(n + 1);
    for (int i = 1; i <= n; ++i)
    {
        cin >> arr[i];
    }

    int s = 1;

    // trimming starting sorted part
    while (s + 1 <= n && arr[s] < arr[s + 1])
    {
        s++;
    }

    // if starting sorted part is till n then already sorted
    if (s == n)
    {
        cout << "yes\n";
        cout << 1 << " " << 1 << '\n';
        return;
    }

    // getting the index till the array part is pure descending
    int e = s;
    while (e + 1 <= n && arr[e] > arr[e + 1])
    {
        e++;
    }

    if (s == 1 && e == n)
    {
        cout << "yes\n";
        cout << 1 << " " << e << '\n';
        return;
    }
    // cout << s << " " << e << '\n';

    reverse(arr.begin() + s, arr.begin() + e + 1);

    // for (const auto &v : arr)
    // {
    //     cout << v << " ";
    // }
    // cout << '\n';
    if (is_sorted(arr.begin(), arr.end()))
    {

        cout << "yes" << '\n';
        cout << s << " " << e << "\n";
    }
    else
    {
        cout << "no\n";
    }
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    // cin >> t;
    while (t--)
    {
        solve();
    }
}

