#include <bits/stdc++.h>
using namespace std;
using ll = long long;

void solve()
{
    int n;
    cin >> n;
    vector<int> a(n + 1);
    for (int i = 1; i <= n; ++i)
    {
        cin >> a[i];
    }

    bool ans = false;

    int left1 = 0, left2 = 0, left3 = 0;

    for (int i = 1; i <= n - 2; ++i)
    {
        left1 += (a[i] == 1);
        left2 += (a[i] == 2);
        left3 += (a[i] == 3);

        if (left1 >= (left2 + left3))
        {

            int mid1 = 0, mid2 = 0, mid3 = 0;

            for (int j = i + 1; j <= n - 1; ++j)
            {
                mid1 += (a[j] == 1);
                mid2 += (a[j] == 2);
                mid3 += (a[j] == 3);
                if ((mid1 + mid2) >= mid3)
                {
                    ans = true;
                    break;
                }
            }
        }

        if (ans)
        {
            break;
        }
    }

    if (ans)
    {
        cout << "YES\n";
    }
    else
    {
        cout << "NO\n";
    }
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    cin >> t;
    while (t--)
    {
        solve();
    }
}

