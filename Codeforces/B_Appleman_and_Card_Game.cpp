#include <bits/stdc++.h>
using namespace std;
using ll = long long;
const ll INF = 1e18;
const ll MOD = 1e9 + 7;

void solve()
{
    ll n, K;
    cin >> n >> K;

    unordered_map<char, ll> m;

    for (ll i = 0; i < n; i++)
    {
        char ch;
        cin >> ch;
        m[ch]++;
    }
    vector<pair<ll, char>> mp(26);
    for (auto const &[k, v] : m)
    {
        mp[k - 'A'] = {v, k};
    }

    sort(mp.rbegin(), mp.rend());

    // for (const auto &[v, k] : mp)
    // {
    //     cout << k << " " << v << '\n';
    // }
    ll ans = 0;
    for (const auto &[v, k] : mp)
    {
        if (K <= v)
        {
            ans += K * K;
            break;
        }
        else
        {
            ans += v * v;
            K -= v;
        }
        if (K <= 0)
        {
            break;
        }
    }
    cout << ans << '\n';
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    // cin >> t;
    while (t--)
    {
        solve();
    }
}

