#include <bits/stdc++.h>
using namespace std;
using ll = long long;

void solve()
{
    int n;
    cin >> n;
    string str;
    cin >> str;

    int c0 = 0, c1 = 0;
    for (const auto &c : str)
    {
        c0 += c == '0';
        c1 += c == '1';
    }

    if (c0 == 0 || c1 == 0)
    {
        cout << 1 << '\n';
        return;
    }

    int len = 0;
    string compressed = "";
    for (int i = 0; i < n; i++)
    {
        if (i == 0 || str[i] != str[i - 1])
        {
            compressed += str[i];
        }
    }
    if (compressed.length() >= 3)
    {
        len = 1;
    }
    else
    {
        len = 2;
    }

    cout << len << '\n';
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    cin >> t;
    while (t--)
    {
        solve();
    }
}

