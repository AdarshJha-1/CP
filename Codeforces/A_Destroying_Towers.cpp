#include <bits/stdc++.h>
using namespace std;
using ll = long long;

void solve()
{
    int n;
    cin >> n;
    int sum = 0;
    int minE = INT_MAX;
    for (int i = 0; i < n; i++)
    {
        int v;
        cin >> v;
        minE = min(minE, v);
        sum += minE;
    }

    cout << sum << "\n";
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    cin >> t;
    while (t--)
    {
        solve();
    }
}

