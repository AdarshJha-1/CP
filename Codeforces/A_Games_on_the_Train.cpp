#include <bits/stdc++.h>
using namespace std;
using ll = long long;

void solve()
{
    int n;
    cin >> n;
    int maxE = INT_MIN;
    int minE = INT_MAX;
    for (int i = 0; i < n; i++)
    {
        int val;
        cin >> val;
        if (val > maxE)
        {
            maxE = val;
        }
        if (val < minE)
        {
            minE = val;
        }
    }
    cout << maxE - minE + 1 << "\n";
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    cin >> t;
    while (t--)
    {
        solve();
    }
}

