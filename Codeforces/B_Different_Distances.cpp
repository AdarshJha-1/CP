#include <bits/stdc++.h>
using namespace std;
using ll = long long;

void solve()
{
    int n;
    cin >> n;
    for (int i = 1; i <= n; i++)
    {
        cout << i << " ";
    }

    for (int i = 1; i <= n; i++)
    {
        cout << i << " ";
    }

    for (int i = 1; i <= n; i++)
    {
        cout << (i % n) + 1 << " ";
    }

    for (int i = 1; i <= n; i++)
    {
        cout << i << " ";
    }

    cout << "\n";
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    cin >> t;
    while (t--)
    {
        solve();
    }
}

