#include <bits/stdc++.h>
using namespace std;
using ll = long long;

void solve()
{
    ll n;
    cin >> n;
    vector<ll> arr(n + 1, 0);
    for (int i = 1; i <= n; i++)
    {
        cin >> arr[i];
    }

    for (int i = 1; i <= n / 2; i++)
    {
        if (2 * i <= n)
        {
            if (arr[i] > arr[2 * i])
            {
                swap(arr[i], arr[2 * i]);
            }
        }
    }

    bool isSorted = true;
    for (int i = 2; i <= n; i++)
    {
        if (arr[i] - arr[i - 1] != 1)
        {
            isSorted = false;
            break;
        }
    }

    cout << (isSorted ? "YES\n" : "NO\n");
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    cin >> t;
    while (t--)
    {
        solve();
    }
}

