#include <bits/stdc++.h>
using namespace std;
using ll = long long;

void solve()
{
    int n;
    cin >> n;

    long long prefix_sum = 0;
    long long min_avg = 1e18;

    for (int i = 1; i <= n; ++i)
    {
        long long val;
        cin >> val;

        prefix_sum += val;
        long long current_avg = prefix_sum / i;

        min_avg = min(min_avg, current_avg);
        cout << min_avg << (i == n ? "" : " ");
    }
    cout << "\n";
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    cin >> t;
    while (t--)
    {
        solve();
    }
}

