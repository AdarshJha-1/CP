#include <bits/stdc++.h>
using namespace std;
using ll = long long;

void solve()
{
    ll n, k;
    cin >> n >> k;
    string str;
    cin >> str;

    vector<int> state(k, 0);
    for (int i = 0; i < n; i++)
    {
        if (str[i] == '1')
        {
            state[i % k]++;
        }
    }

    bool isZero = true;
    for (int i = 0; i < k; i++)
    {
        if (state[i] % 2 != 0)
        {
            isZero = false;
            break;
        }
    }
    cout << (isZero ? "YES\n" : "NO\n");
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    cin >> t;
    while (t--)
    {
        solve();
    }
}

