#include <bits/stdc++.h>
using namespace std;
using ll = long long;

void solve()
{
    vector<vector<int>> mat(3, vector<int>(6, 0));
    for (int i = 0; i < 3; i++)
    {
        for (int j = 0; j < 6; j++)
        {
            cin >> mat[i][j];
        }
    }

    int ans = 0;

    for (int i = 0; i < 6; i++)
    {
        for (int j = 0; j < 6; j++)
        {
            for (int k = 0; k < 6; k++)
            {
                if (
                    mat[0][i] == 4 && mat[1][j] == 5 && mat[2][k] == 6 ||
                    mat[0][i] == 4 && mat[1][j] == 6 && mat[2][k] == 5 ||
                    mat[0][i] == 5 && mat[1][j] == 4 && mat[2][k] == 6 ||
                    mat[0][i] == 5 && mat[1][j] == 6 && mat[2][k] == 4 ||
                    mat[0][i] == 6 && mat[1][j] == 5 && mat[2][k] == 4 ||
                    mat[0][i] == 6 && mat[1][j] == 4 && mat[2][k] == 5)
                {
                    ans++;
                }
            }
        }
    }

    printf("%.10f\n", ans / 216.0);
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    // cin >> t;
    while (t--)
    {
        solve();
    }
}

