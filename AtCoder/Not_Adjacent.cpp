#include <bits/stdc++.h>
using namespace std;
using ll = long long;

// f you MOD
const ll MOD = 998244353;
void solve()
{
    string str;
    cin >> str;

    ll ans = 0;
    ll s = 0, e = 0;
    for (; e < str.size() - 1; e++)
    {
        if (str[e] == str[e + 1])
        {
            ll n = (e - s) + 1;
            ans = (ans + (n * (n + 1)) / 2) % MOD;
            s = e + 1;
        }
    }
    ll n = (e - s) + 1;
    ans = (ans + (n * (n + 1)) / 2) % MOD;

    cout << ans << endl;
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    // cin >> t;
    while (t--)
    {
        solve();
    }
}

