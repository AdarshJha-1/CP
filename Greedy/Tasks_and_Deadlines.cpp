#include <bits/stdc++.h>
using namespace std;
using ll = long long;

void solve()
{
    ll n;
    cin >> n;
    vector<pair<ll, ll>> arr(n);
    for (auto &vp : arr)
    {
        cin >> vp.first >> vp.second;
    }

    sort(arr.begin(), arr.end());

    ll ans = 0;
    ll t = 0;
    for (const auto &vp : arr)
    {
        t += vp.first;
        ans += (vp.second - t);
    }

    cout << ans << "\n";
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    // cin >> t;
    while (t--)
    {
        solve();
    }
}

