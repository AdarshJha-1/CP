#include <bits/stdc++.h>
using namespace std;
using ll = long long;

void solve()
{
    ll n;
    cin >> n;

    ll max_time = 0;
    ll t_sum = 0;
    for (ll i = 0; i < n; i++)
    {
        ll temp;
        cin >> temp;
        t_sum += temp;
        max_time = max(max_time, temp);
    }

    cout << max(max_time * 2, t_sum) << '\n';
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    // cin >> t;
    while (t--)
    {
        solve();
    }
}

