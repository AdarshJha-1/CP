#include <bits/stdc++.h>
using namespace std;
using ll = long long;

set<string> store;

void get_all_strings(string &str, string &temp, vector<bool> seen, int idx)
{
    seen[idx] = true;
    temp.push_back(str[idx]);
    if (temp.size() == str.size())
    {
        store.insert(temp);
    }

    for (int i = 0; i < str.size(); i++)
    {
        if (!seen[i])
        {
            get_all_strings(str, temp, seen, i);
        }
    }
    temp.pop_back();
    seen[idx] = false;
}

void solve()
{
    string str;
    cin >> str;

    string temp = "";
    vector<bool> seen(str.size(), false);
    for (int i = 0; i < str.size(); i++)
    {
        get_all_strings(str, temp, seen, i);
    }

    cout << store.size() << "\n";
    for (const auto &curr_s : store)
    {
        cout << curr_s << "\n";
    }
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    // cin >> t;
    while (t--)
    {
        solve();
    }
}

