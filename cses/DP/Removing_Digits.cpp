#include <bits/stdc++.h>
using namespace std;
using ll = long long;
const ll INF = 1e18;

void solve()
{
    ll n;
    cin >> n;

    vector<ll> dp(n + 1, INF);
    dp[0] = 0;
    for (ll i = 1; i <= n; i++)
    {
        for (const auto d : to_string(i))
        {
            ll digit = d - '0';
            dp[i] = min(dp[i], (dp[i - digit] + 1));
        }
    }
    cout << dp[n] << '\n';
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    // cin >> t;
    while (t--)
    {
        solve();
    }
}

