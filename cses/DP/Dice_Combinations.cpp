#include <bits/stdc++.h>
using namespace std;
using ll = long long;

vector<ll> dp;
const int MOD = 1e9 + 7;

ll sol(ll cs, int n)
{
    if (cs > n)
    {
        return 0;
    }
    if (cs == n)
    {
        return 1;
    }
    if (dp[cs] != -1)
    {
        return dp[cs];
    }
    ll c = 0;
    for (int i = 1; i <= 6; i++)
    {
        c = (c + sol(cs + i, n)) % MOD;
    }
    return dp[cs] = c;
}

void solve()
{
    int n;
    cin >> n;

    dp.assign(n + 1, -1);

    cout << sol(0, n) << '\n';
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    // cin >> t;
    while (t--)
    {
        solve();
    }
}

