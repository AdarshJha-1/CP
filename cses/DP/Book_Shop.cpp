#include <bits/stdc++.h>
using namespace std;
using ll = long long;
const ll INF = 1e18;
const ll MOD = 1e9 + 7;

int dp[100001][1001];

int sol(vector<int> &price, vector<int> &pages, int n, int x, int i)
{
    if (i >= n)
    {
        return 0;
    }
    if (dp[x][i] != -1)
    {
        return dp[x][i];
    }
    int skip = sol(price, pages, n, x, i + 1);
    int take = 0;
    if (x - price[i] >= 0)
    {
        take = pages[i] + sol(price, pages, n, x - price[i], i + 1);
    }

    return dp[x][i] = max(take, skip);
}

void solve()
{
    int n, x;
    cin >> n >> x;
    vector<int> price(n), pages(n);
    for (auto &p : price)
    {
        cin >> p;
    }
    for (auto &p : pages)
    {
        cin >> p;
    }

    memset(dp, -1, sizeof(dp));

    int ans = sol(price, pages, n, x, 0);
    cout << ans << '\n';
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    // cin >> t;
    while (t--)
    {
        solve();
    }
}

