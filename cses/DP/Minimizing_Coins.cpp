#include <bits/stdc++.h>
using namespace std;
using ll = long long;
const ll INF = 1e18;

void solve()
{
    ll n, x;
    cin >> n >> x;
    vector<ll> coins(n);
    for (auto &c : coins)
    {
        cin >> c;
    }

    vector<ll> dp(x + 1, INF);
    dp[0] = 0;

    for (ll i = 1; i <= x; i++)
    {
        for (int j = 0; j < n; j++)
        {
            if (i - coins[j] >= 0)
            {
                dp[i] = min(dp[i], (dp[i - coins[j]] + 1));
            }
        }
    }

    cout << (dp[x] == INF ? -1 : dp[x]) << '\n';
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    // cin >> t;
    while (t--)
    {
        solve();
    }
}

