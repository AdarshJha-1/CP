#include <bits/stdc++.h>
using namespace std;
using ll = long long;
const ll INF = 1e18;
const ll MOD = 1e9 + 7;

void solve()
{
    ll n;
    cin >> n;
    vector<string> grid(n);
    for (auto &g : grid)
    {
        cin >> g;
    }
    if (grid[0][0] == '*')
    {
        cout << 0 << '\n';
        return;
    }
    vector<vector<ll>> dp(n, vector<ll>(n, 0));
    for (int i = 0; i < n; i++)
    {
        for (int j = 0; j < n; j++)
        {
            if (i == 0 && i == j)
            {
                dp[i][j] = 1;
                continue;
            }
            // left
            if (j - 1 >= 0 && grid[i][j] == '.')
            {
                dp[i][j] = (dp[i][j] + dp[i][j - 1]) % MOD;
            }

            // down
            if (i - 1 >= 0 && grid[i][j] == '.')
            {
                dp[i][j] = (dp[i][j] + dp[i - 1][j]) % MOD;
            }
        }
    }
    cout << dp[n - 1][n - 1] << "\n";
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    // cin >> t;
    while (t--)
    {
        solve();
    }
}

