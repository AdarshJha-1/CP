#include <bits/stdc++.h>
using namespace std;
using ll = long long;
const ll INF = 1e18;
const int MOD = 1e9 + 7;

void solve()
{
    ll n, x;
    cin >> n >> x;
    vector<ll> coins(n);
    for (auto &c : coins)
    {
        cin >> c;
    }

    vector<ll> count(x + 1, 0);
    count[0] = 1;

    for (ll i = 1; i <= x; i++)
    {
        for (ll j = 0; j < n; j++)
        {
            ll remain = i - coins[j];
            if (remain >= 0)
            {
                count[i] = (count[i] + count[remain]) % MOD;
            }
        }
    }
    cout << count[x] << "\n";
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    // cin >> t;
    while (t--)
    {
        solve();
    }
}

