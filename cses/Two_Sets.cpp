#include <bits/stdc++.h>
using namespace std;
using ll = long long;

void solve()
{
    ll n;
    cin >> n;
    ll total_sum = (n * (n + 1)) / 2;
    if (total_sum % 2 != 0)
    {
        cout << "NO\n";
        return;
    }
    cout << "YES\n";
    ll i = n;
    ll half_1 = total_sum / 2;
    unordered_map<ll, bool> used;
    vector<ll> s1, s2;
    while (half_1)
    {
        if (used.find(i) == used.end() && half_1 >= i)
        {
            half_1 -= i;
            used[i] = true;
            s1.push_back(i);
        }
        i--;
    }
    for (ll i = 1; i < n; i++)
    {
        if (used.find(i) == used.end())
        {
            s2.push_back(i);
        }
    }

    cout << s1.size() << "\n";
    for (const auto &v : s1)
    {
        cout << v << " ";
    }
    cout << "\n";

    cout << s2.size() << "\n";
    for (const auto &v : s2)
    {
        cout << v << " ";
    }
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    // cin >> t;
    while (t--)
    {
        solve();
    }
}

