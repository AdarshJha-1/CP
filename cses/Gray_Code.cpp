string to_b_string(int num, int len)
{
    string temp = "";
    if (num == 0)
    {
        temp += "0";
    }
    while (num > 0)
    {
        temp += (num & 1) ? "1" : "0";
        num >>= 1;
    }

    int req_len = len - temp.size();
    while (req_len--)
    {
        temp += "0";
    }

    reverse(temp.begin(), temp.end());
    return temp;
}

