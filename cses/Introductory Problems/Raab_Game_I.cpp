#include <bits/stdc++.h>
using namespace std;
using ll = long long;

void solve()
{
    int n, a, b;
    cin >> n >> a >> b;
    if (a + b > n || a == n || b == n || (a == 0 && b != 0) || (b == 0 && a != 0))
    {
        cout << "NO\n";
    }
    else
    {
        cout << "YES\n";
        vector<int> ans(n + 1, 0);

        // tied
        int i = 1;
        for (; i <= n - a - b; i++)
        {
            ans[i] = i;
        }

        int for_w = b + i;
        int for_l = i;

        // won
        for (; i <= n - b; i++)
        {
            ans[i] = for_w++;
        }

        // loss
        for (; i <= n; i++)
        {
            ans[i] = for_l++;
        }

        for (int i = 1; i <= n; i++)
        {
            cout << ans[i] << " ";
        }
        cout << "\n";

        for (int i = 1; i <= n; i++)
        {
            cout << i << " ";
        }
        cout << "\n";
    }
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    cin >> t;
    while (t--)
    {
        solve();
    }
}

