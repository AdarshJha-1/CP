#include <bits/stdc++.h>
using namespace std;
using ll = long long;

void solve()
{
    // idk it solvable by using "Legendre's Formula" have to check on YT
    ll n;
    cin >> n;
    ll p = 5;
    ll count = 0;
    while (p <= n)
    {
        count += (n / p);
        p *= 5;
    }

    cout << count << "\n";
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    // cin >> t;
    while (t--)
    {
        solve();
    }
}

