#include <bits/stdc++.h>
using namespace std;
using ll = long long;

ll ans = 0;

bool is_safe(vector<string> &board, int row, int col, int n)
{
    // top
    for (int i = row - 1; i >= 0; i--)
    {
        if (board[i][col] == 'Q')
        {
            return false;
        }
    }

    // left top
    for (int i = row - 1, j = col - 1; i >= 0 && j >= 0; i--, j--)
    {
        if (board[i][j] == 'Q')
        {
            return false;
        }
    }

    // right top
    for (int i = row - 1, j = col + 1; i >= 0 && j < n; i--, j++)
    {
        if (board[i][j] == 'Q')
        {
            return false;
        }
    }

    return true;
}

void sol(vector<string> &board, int n, int row)
{
    if (row >= n)
    {
        ans++;
        return;
    }

    for (int i = 0; i < n; i++)
    {
        if (board[row][i] == '.' && is_safe(board, row, i, n))
        {
            board[row][i] = 'Q';
            sol(board, n, row + 1);
            board[row][i] = '.';
        }
    }
}

void solve()
{

    int n = 8;
    vector<string> board(n);

    for (int i = 0; i < n; i++)
    {
        cin >> board[i];
    }

    sol(board, n, 0);

    cout << ans << "\n";
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    // cin >> t;
    while (t--)
    {
        solve();
    }
}

