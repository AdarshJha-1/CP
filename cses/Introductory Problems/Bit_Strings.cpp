#include <bits/stdc++.h>
using namespace std;
using ll = long long;

constexpr int MOD = 1e9 + 7;

void solve()
{
    ll n;
    cin >> n;

    ll ans = 1;
    while (n-- > 0)
    {
        ans = (ans * 2) % MOD;
    }

    cout << ans << "\n";
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    // cin >> t;
    while (t--)
    {
        solve();
    }
}

