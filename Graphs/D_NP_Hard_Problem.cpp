#include <bits/stdc++.h>
using namespace std;
using ll = long long;

void solve()
{
    ll n, m;
    cin >> n >> m;
    vector<vector<ll>> adj(n + 1);
    for (size_t i = 0; i < m; ++i)
    {
        ll u, v;
        cin >> u >> v;
        adj[u].push_back(v);
        adj[v].push_back(u);
    }

    vector<int> color(n + 1, -1);

    for (size_t i = 1; i <= n; ++i)
    {
        if (color[i] == -1)
        {
            color[i] = 0;
            queue<ll> q;
            q.push(i);

            while (!q.empty())
            {
                ll curr = q.front();
                q.pop();
                for (const auto &nei : adj[curr])
                {
                    if (color[nei] == color[curr])
                    {
                        cout << -1 << "\n";
                        return;
                    }
                    if (color[nei] == -1)
                    {
                        color[nei] = 1 - color[curr];
                        q.push(nei);
                    }
                }
            }
        }
    }
    vector<ll> pariTakeC0;
    vector<ll> aryaTakeC1;
    for (size_t i = 1; i <= n; ++i)
    {
        if (color[i] == 0)
        {
            pariTakeC0.push_back(i);
        }
        else
        {
            aryaTakeC1.push_back(i);
        }
    }

    cout << pariTakeC0.size() << '\n';
    for (const auto &v : pariTakeC0)
    {
        cout << v << " ";
    }
    cout << "\n";
    cout << aryaTakeC1.size() << '\n';
    for (const auto &v : aryaTakeC1)
    {
        cout << v << " ";
    }
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    // cin >> t;
    while (t--)
    {
        solve();
    }
}

