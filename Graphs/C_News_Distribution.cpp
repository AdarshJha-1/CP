#include <bits/stdc++.h>
using namespace std;
using ll = long long;

class DSU
{
public:
    vector<ll> parent;
    vector<ll> grpSize;
    DSU(int n)
    {
        parent.resize(n + 1);
        grpSize.resize(n + 1, 1);
        for (size_t i = 1; i <= n; ++i)
        {
            parent[i] = i;
        }
    }
    ll find(ll v)
    {
        if (parent[v] == v)
        {
            return v;
        }
        return parent[v] = find(parent[v]);
    }
    void union_sets(int u, int v)
    {
        int root_u = find(u);
        int root_v = find(v);

        if (root_u != root_v)
        {
            if (root_u < root_v)
            {
                parent[root_v] = root_u;
                grpSize[root_u] += grpSize[root_v];
            }
            else
            {
                parent[root_u] = root_v;
                grpSize[root_v] += grpSize[root_u];
            }
        }
    }
};

void solve()
{
    ll n, m;
    cin >> n >> m;
    DSU dsu(n);
    for (size_t i = 0; i < m; ++i)
    {
        ll s;
        cin >> s;
        if (s == 0)
        {
            continue;
        }
        ll u;
        cin >> u;
        for (size_t j = 1; j < s; j++)
        {
            ll v;
            cin >> v;
            dsu.union_sets(u, v);
        }
    }

    for (size_t i = 1; i <= n; ++i)
    {
        ll root = dsu.find(i);
        cout << dsu.grpSize[root] << " ";
    }
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    // cin >> t;
    while (t--)
    {
        solve();
    }
}

